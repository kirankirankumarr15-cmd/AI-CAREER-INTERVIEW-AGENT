export function getQuestionsBySubject(subjectId: string): PracticeQuestion[] {
  const norm = (subjectId || '').toLowerCase().trim();
  return PRACTICE_QUESTIONS.filter(
    (q) => q.subjectId.toLowerCase() === norm || (norm === 'sql' && q.subjectId === 'dbms')
  );
}

export function getQuestionById(id: string): PracticeQuestion | undefined {
  if (!id) return undefined;
  const decoded = decodeURIComponent(id).trim().toLowerCase();
  return PRACTICE_QUESTIONS.find((q) => q.id.toLowerCase() === decoded);
}
